/**
 * 摘要から箱を決める。分からなければ `null`。
 *
 * `null` は「その他」ではない。**その他は「調べた上でどれでもない」**で、
 * こちらは「分からない」。混ぜると、分からないものが分類済みの顔をする。
 */
export function categorise(description: string): string | null {
  const text = fold(description);
  if (!text) return null;
  // 店名が届いていないものは、分けようがない。
  if (text.includes(fold('(利用先不明)'))) return null;
  for (const rule of CATEGORY_RULES) {
    for (const needle of rule.match) {
      if (text.includes(fold(needle))) return rule.category;
    }
  }
  return null;
}

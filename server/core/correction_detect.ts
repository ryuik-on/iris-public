/**
 * 利用者が、IRIS の直前の答えを「違う」と直した発言かどうか。
 *
 * 「毎回こっちで直してる」（利用者、2026-10-02）。直した回数は記録に残っていなかったので、
 * どの種類の誤りが多いかが、数字で見えなかった。ここは、**短い発言の中の、直しの言い方**だけを
 * 拾う。確実な判定ではない（「訂正らしい発言」として記録するだけで、何も止めない・変えない）。
 *
 * 長い発言は、新しい頼みごとであることが多いので拾わない（「食い違いを確認して」のような、
 * 「違い」を含むだけの頼みごとを、直しと数えないため）。
 */
const PATTERNS: RegExp[] = [
  /^(いや|いえ|ううん)?[、,\s]*(違う|ちがう|違います|違うよ|違うな)/,
  /(それ|これ|今の|さっきの|その答え|その情報)(は|が)?(間違|違)/,
  /間違(って|え)(る|てる|ています|ている|ました|た)/,
  /(そう|それ)じゃない/,
  /(おかしい|変だ)(よ|です|な|ね)?[。!！?？]*$/,
  /誤(報|り|答)/,
  /(嘘|うそ)(だ|でしょ|つく|ついて)/,
  /そんなこと(は)?(ない|言ってない)/,
  /(合って|あって)(ない|いない|ません)/,
];

export function looksLikeCorrection(text: string): boolean {
  const t = String(text ?? '').trim();
  if (!t || t.length > 120) return false;
  return PATTERNS.some((p) => p.test(t));
}

  /**
   * The narrow readonly pair, which is what the server itself says it takes.
   *
   * These were widened to `calendar.readonly` on the theory that Google's
   * Calendar MCP server wanted something broader, because every `tools/call`
   * came back "The caller does not have permission". Widening changed nothing:
   * the same error, with the same tools. Reading the server's own
   * `oauth-protected-resource` metadata afterwards showed both of these listed
   * in `scopes_supported` — so the narrow pair was never the problem, and the
   * broader grant bought exactly nothing. Reverted, because a permission kept
   * "just in case" is a permission nobody can justify later.
   *
   * What is established, and what is not:
   *
   *   The credential works. The same token reads the calendar list and events
   *   through the ordinary Calendar REST API, 200 both times.
   *
   *   The Calendar MCP API is enabled on the project — the earlier "has not
   *   been used in project" error is gone.
   *
   *   An explicit `x-goog-user-project` quota project does not help.
   *
   *   `tools/list` needs no authorization, so a connection reporting
   *   "connected, 9 tools" says nothing about whether the credential works.
   *   Only a `tools/call` does. A verification that checked for bytes rather
   *   than for `isError` reported success on this exact failure.
   *
   * The remaining candidate is Google-side: this OAuth client is External and
   * in Testing, and the MCP endpoint may require a published or verified app.
   * Unconfirmed. Until it is, the REST API is the path that works.
   */

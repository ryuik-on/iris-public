import { OAuthStore, StoredTokens } from './oauth_store.js';

/**
 * The MCP SDK's OAuth provider, backed by IRIS's token store.
 *
 * The SDK drives the protocol — discovery, PKCE, refresh, the 401 dance. What
 * it delegates is where secrets live and how a person is sent to the consent
 * screen, which is exactly the part that has to be decided per application.
 *
 * IRIS is a server with no browser of its own, so `redirectToAuthorization`
 * cannot open anything. It records the URL and lets an endpoint hand it to
 * whoever asked. That is not a workaround — a background service silently
 * opening a consent screen would be worse.
 */

export interface IrisOAuthOptions {
  serverId: string;
  clientId: string;
  clientSecret?: string;
  redirectUri: string;
  scopes: string[];
  /**
   * Extra query parameters for the authorization request.
   *
   * Exists for Google's two non-standard ones. Without `access_type=offline`
   * Google issues no refresh token at all, so the credential dies in an hour
   * and the person is sent back to a consent screen — and a permission prompt
   * that appears hourly is one people learn to click through without reading,
   * which is a worse security outcome than the long-lived token it was
   * avoiding. `prompt=consent` is needed alongside it because Google returns a
   * refresh token only on a fresh grant, and this account has already granted.
   */
  authorizationParams?: Record<string, string>;
  store: OAuthStore;
  onEvent?: (event: { type: string; detail?: Record<string, any> }) => void;
}

export class IrisOAuthProvider {
  /** Set when the SDK asks for authorization; read by the endpoint. */
  private pendingAuthorizationUrl: URL | null = null;
  private pendingVerifier: string | null = null;
  private currentState: string | null = null;
  /**
   * The verifier for the flow currently being exchanged.
   *
   * Separate from `pendingVerifier` because the two have different lifetimes.
   * `auth()` invalidates and retries once when an exchange fails, and its
   * invalidation clears the verifier — which for an authorization-code
   * exchange can never help: the verifier has to match the challenge that was
   * put in the URL the user already consented to, so a retry without it cannot
   * succeed, and the PKCE error it raises replaces whatever the server
   * actually objected to. Keeping it here means the retry runs with the right
   * verifier and the original error is the one that surfaces.
   *
   * Cleared by `beginNewFlow`, because a genuinely new authorization must
   * never reuse an old flow's verifier.
   */
  private exchangeVerifier: string | null = null;

  constructor(private options: IrisOAuthOptions) {}

  get redirectUrl(): string {
    return this.options.redirectUri;
  }

  get clientMetadata() {
    return {
      client_name: 'IRIS',
      redirect_uris: [this.options.redirectUri],
      grant_types: ['authorization_code', 'refresh_token'],
      response_types: ['code'],
      token_endpoint_auth_method: this.options.clientSecret
        ? 'client_secret_post'
        : 'none',
      scope: this.options.scopes.join(' '),
    };
  }

  clientInformation() {
    return {
      client_id: this.options.clientId,
      ...(this.options.clientSecret ? { client_secret: this.options.clientSecret } : {}),
    };
  }

  /**
   * The CSRF state.
   *
   * Generated by opening a flow row, so the value that goes out is the same
   * value that can be claimed back — a state nobody recorded is a callback
   * nobody asked for.
   */
  state(): string {
    if (!this.currentState) {
      this.currentState = this.options.store.beginFlow(
        this.options.serverId,
        this.pendingVerifier ?? ''
      );
    }
    return this.currentState;
  }

  tokens(): StoredTokens | undefined {
    return this.options.store.getTokens(this.options.serverId);
  }

  saveTokens(tokens: StoredTokens): void {
    this.options.store.saveTokens(this.options.serverId, tokens);
    this.options.onEvent?.({
      type: 'oauth.tokens_saved',
      detail: {
        server: this.options.serverId,
        // Whether a refresh token arrived decides whether this survives an
        // hour. Worth recording; the token itself never is.
        hasRefreshToken: Boolean(tokens.refresh_token),
        scope: tokens.scope ?? null,
      },
    });
  }

  saveCodeVerifier(codeVerifier: string): void {
    this.pendingVerifier = codeVerifier;
    this.exchangeVerifier = codeVerifier;
    // Attached to the state already issued, never rotated. The SDK may call
    // this after building the authorization URL, and changing the state at
    // that point guarantees the callback cannot be matched.
    if (this.currentState) {
      this.options.store.setFlowVerifier(this.currentState, codeVerifier);
    }
  }

  /**
   * Discards any half-finished flow so a new authorization starts clean.
   *
   * Without this the provider reuses the state from a previous attempt, and an
   * abandoned attempt quietly poisons the next one.
   */
  beginNewFlow(): void {
    if (this.currentState) this.options.store.claimFlow(this.currentState);
    this.currentState = null;
    this.pendingVerifier = null;
    this.exchangeVerifier = null;
    this.pendingAuthorizationUrl = null;
  }

  codeVerifier(): string {
    const verifier = this.pendingVerifier ?? this.exchangeVerifier;
    if (!verifier) throw new Error('PKCE verifier がありません。認可を開始してください。');
    return verifier;
  }

  /**
   * Records where the user has to go, rather than going there.
   *
   * A resident service has no browser, and one that could open a consent
   * screen unprompted would be a worse thing to own than one that cannot.
   */
  redirectToAuthorization(authorizationUrl: URL): void {
    // Applied here rather than passed through `auth()`, which has no parameter
    // for provider-specific extras.
    for (const [key, value] of Object.entries(this.options.authorizationParams ?? {})) {
      authorizationUrl.searchParams.set(key, value);
    }
    this.pendingAuthorizationUrl = authorizationUrl;
    this.options.onEvent?.({
      type: 'oauth.authorization_required',
      detail: { server: this.options.serverId, host: authorizationUrl.host },
    });
  }

  /** The URL an endpoint should hand to the person, once. */
  takeAuthorizationUrl(): URL | null {
    const url = this.pendingAuthorizationUrl;
    this.pendingAuthorizationUrl = null;
    return url;
  }

  invalidateCredentials(scope: 'all' | 'client' | 'tokens' | 'verifier' | 'discovery'): void {
    if (scope === 'all' || scope === 'tokens') this.options.store.revoke(this.options.serverId);
    if (scope === 'all' || scope === 'verifier') {
      this.pendingVerifier = null;
      if (this.currentState) this.options.store.claimFlow(this.currentState);
      this.currentState = null;
    }
    this.options.onEvent?.({ type: 'oauth.invalidated', detail: { server: this.options.serverId, scope } });
  }
}

/**
 * Scopes Google's MCP servers document.
 *
 * Read-only wherever a read-only variant exists. `gmail.compose` is
 * deliberately absent: composing is an outbound capability, and IRIS's own
 * rules already forbid an inferred run from reaching one. Asking for it
 * anyway would put the capability behind a consent screen the user clicks
 * once, rather than behind the approval boundary that was built for it.
 */
